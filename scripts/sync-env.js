import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const rootEnvPath = path.join(rootDir, '.env');
const rootEnvExamplePath = path.join(rootDir, '.env.example');

// If root .env does not exist, copy from .env.example
if (!fs.existsSync(rootEnvPath) && fs.existsSync(rootEnvExamplePath)) {
  fs.copyFileSync(rootEnvExamplePath, rootEnvPath);
  console.log('Created root .env from .env.example');
}

if (!fs.existsSync(rootEnvPath)) {
  console.warn('No root .env file found to sync.');
  process.exit(0);
}

// Parse root .env
function parseEnv(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const env = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      const val = trimmed.slice(eqIdx + 1).trim();
      env[key] = val;
    }
  }
  return env;
}

const config = parseEnv(rootEnvPath);

// Ensure proper DB URI with Database name appended if needed
const dbName = config.MONGO_DB_NAME || 'fintech_copilot';
let backendMongoUri = config.MONGODB_URI || 'mongodb://127.0.0.1:27017/fintech_copilot';

// If MONGODB_URI ends with / or hostname without database name, append database name
if (backendMongoUri.endsWith('/')) {
  backendMongoUri = `${backendMongoUri}${dbName}`;
} else if (!backendMongoUri.includes('/', backendMongoUri.indexOf('://') + 3)) {
  backendMongoUri = `${backendMongoUri}/${dbName}`;
}

